/** RIR detection from first octet (IPv4) or prefix (rough). */
export function detectRIR(ip: string): string {
  if (!ip.includes(".") || ip.includes(":")) {
    // Rough IPv6 prefixes
    if (/^(2a0[0-9a-f]|2a1)/i.test(ip)) return "RIPE NCC";
    if (/^(26|2800|2c0)/i.test(ip)) return "LACNIC / ARIN / AfriNIC";
    return "IANA";
  }
  const a = Number(ip.split(".")[0]);
  if ((a >= 2 && a <= 46) || (a >= 77 && a <= 95) || (a >= 126 && a <= 174) || (a >= 192 && a <= 195) || (a >= 212 && a <= 223)) {
    return "RIPE NCC"; // European ranges (approximation for MENA/Europe)
  }
  if ((a >= 47 && a <= 76) || a === 96 || (a >= 175 && a <= 191) || (a >= 198 && a <= 199) || (a >= 204 && a <= 209)) {
    return "ARIN";
  }
  if ((a >= 1 && a <= 1) || (a >= 14 && a <= 15) || (a >= 27) || (a >= 60 && a <= 62) || (a >= 110 && a <= 112) || (a >= 202)) {
    return "APNIC";
  }
  if (a >= 196 || (a >= 179)) return "AFRINIC";
  if ((a >= 100) || (a >= 177) || (a >= 181)) return "LACNIC";
  return "IANA";
}
